-- 1. HOSPITALS TABLE
CREATE TABLE IF NOT EXISTS public.hospitals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    area TEXT NOT NULL,
    lat NUMERIC(9,6) DEFAULT 22.5726,
    lng NUMERIC(9,6) DEFAULT 88.3639,
    distance NUMERIC(5,2) NOT NULL DEFAULT 0,
    general INTEGER NOT NULL DEFAULT 0,
    general_total INTEGER NOT NULL DEFAULT 50,
    icu INTEGER NOT NULL DEFAULT 0,
    icu_total INTEGER NOT NULL DEFAULT 15,
    oxygen INTEGER NOT NULL DEFAULT 0,
    oxygen_total INTEGER NOT NULL DEFAULT 25,
    staff INTEGER NOT NULL DEFAULT 0,
    categories TEXT[] NOT NULL DEFAULT '{}',
    facilities TEXT[] NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. EMERGENCY REQUESTS TABLE
CREATE TABLE IF NOT EXISTS public.emergency_requests (
    id BIGINT PRIMARY KEY,
    patient_name TEXT NOT NULL,
    age INTEGER NOT NULL,
    contact TEXT NOT NULL,
    category TEXT NOT NULL,
    facility TEXT NOT NULL,
    location TEXT NOT NULL,
    lat NUMERIC(9,6),
    lng NUMERIC(9,6),
    triage_score INTEGER DEFAULT 0,
    severity TEXT DEFAULT 'STABLE',
    notes TEXT DEFAULT '',
    status TEXT NOT NULL DEFAULT 'Matching',
    hospital_id BIGINT REFERENCES public.hospitals(id) ON DELETE SET NULL,
    owner TEXT NOT NULL DEFAULT 'guest',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3. RESERVATIONS TABLE
CREATE TABLE IF NOT EXISTS public.reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT REFERENCES public.emergency_requests(id) ON DELETE CASCADE,
    hospital_id BIGINT REFERENCES public.hospitals(id) ON DELETE CASCADE,
    patient_name TEXT NOT NULL,
    bed_type TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Pending',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- ============================================
-- ENABLE ROW LEVEL SECURITY (RLS)
-- ============================================

ALTER TABLE public.hospitals ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.emergency_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reservations ENABLE ROW LEVEL SECURITY;

